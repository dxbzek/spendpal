// The HTML of the printable monthly report.
//
// The print window is written with document.write and has the app's own
// origin, so any markup in it runs with the user's session. Category names are
// free text (typed, restored from a backup file, or read from a statement by
// the AI), so every value that goes into the page is escaped here first.

/** Make a value safe to place in HTML text or in a quoted attribute. */
export function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c] as string),
  );
}

export interface MonthlyReportData {
  monthLabel: string;
  currency: string;
  txCount: number;
  totalIncome: number;
  totalExpenses: number;
  netSavings: number;
  categories: Array<{ category: string; total: number }>;
  budgets: Array<{ category: string; spent: number; amount: number }>;
  /** Today's date as text, for the footer. */
  generatedOn: string;
}

export function buildMonthlyReportHtml(report: MonthlyReportData, fmt: (n: number) => string): string {
  const e = escapeHtml;
  const money = (n: number) => e(fmt(n));

  const rows = report.categories.map(c =>
    `<tr><td>${e(c.category)}</td><td style="text-align:right">${money(Math.round(c.total))}</td></tr>`
  ).join('');

  const budgetRows = report.budgets.length > 0
    ? report.budgets.map(b => {
        const pct = b.amount > 0 ? Math.round((b.spent / b.amount) * 100) : 0;
        const status = pct >= 100 ? 'Over' : pct >= 75 ? 'High' : 'OK';
        return `<tr><td>${e(b.category)}</td><td style="text-align:right">${money(Math.round(b.spent))}</td><td style="text-align:right">${money(b.amount)}</td><td style="text-align:center">${status}</td></tr>`;
      }).join('')
    : '<tr><td colspan="4" style="color:#888">No budgets set</td></tr>';

  return `
      <!DOCTYPE html>
      <html>
      <head>
        <title>SpendPal — ${e(report.monthLabel)} Report</title>
        <style>
          body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; padding: 40px; color: #111; max-width: 700px; margin: 0 auto; }
          h1 { font-size: 24px; margin-bottom: 4px; }
          .subtitle { color: #666; font-size: 14px; margin-bottom: 32px; }
          .summary { display: flex; gap: 24px; margin-bottom: 32px; flex-wrap: wrap; }
          .summary-card { background: #f8faf8; border: 1px solid #d1e8d4; border-radius: 12px; padding: 16px 24px; flex: 1; min-width: 140px; }
          .summary-card .label { font-size: 12px; color: #666; margin-bottom: 4px; }
          .summary-card .value { font-size: 20px; font-weight: 700; }
          .income { color: #1e7a3c; }
          .expense { color: #c0392b; }
          .savings { color: ${report.netSavings >= 0 ? '#1e7a3c' : '#c0392b'}; }
          h2 { font-size: 16px; margin-bottom: 12px; color: #333; border-bottom: 1px solid #e5e7eb; padding-bottom: 6px; }
          table { width: 100%; border-collapse: collapse; margin-bottom: 32px; font-size: 13px; }
          th { text-align: left; padding: 8px 10px; background: #f0f9f4; font-size: 11px; text-transform: uppercase; letter-spacing: 0.05em; color: #555; }
          td { padding: 8px 10px; border-bottom: 1px solid #f0f0f0; }
          .footer { margin-top: 40px; font-size: 11px; color: #aaa; text-align: center; }
          @media print { body { padding: 20px; } }
        </style>
      </head>
      <body>
        <h1>SpendPal Monthly Report</h1>
        <div class="subtitle">${e(report.monthLabel)} &nbsp;·&nbsp; ${e(report.txCount)} transactions &nbsp;·&nbsp; ${e(report.currency)}</div>

        <div class="summary">
          <div class="summary-card"><div class="label">Income</div><div class="value income">${money(Math.round(report.totalIncome))}</div></div>
          <div class="summary-card"><div class="label">Expenses</div><div class="value expense">${money(Math.round(report.totalExpenses))}</div></div>
          <div class="summary-card"><div class="label">Net Savings</div><div class="value savings">${money(Math.round(report.netSavings))}</div></div>
        </div>

        <h2>Expenses by Category</h2>
        <table>
          <thead><tr><th>Category</th><th style="text-align:right">Amount</th></tr></thead>
          <tbody>${rows || '<tr><td colspan="2" style="color:#888">No expenses this month</td></tr>'}</tbody>
        </table>

        <h2>Budget Performance</h2>
        <table>
          <thead><tr><th>Budget</th><th style="text-align:right">Spent</th><th style="text-align:right">Limit</th><th style="text-align:center">Status</th></tr></thead>
          <tbody>${budgetRows}</tbody>
        </table>

        <div class="footer">Generated by SpendPal on ${e(report.generatedOn)}</div>
        <script>window.onload = function() { window.print(); }</script>
      </body>
      </html>
    `;
}
